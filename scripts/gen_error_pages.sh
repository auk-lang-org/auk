#!/usr/bin/env bash
# Generate compiler/src/error_pages.auk: one `#embed` extern per docs/errors/<code>.md page, so
# the Auk port's `explain` carries the pages in its binary as Rust's `include_str!` does
# (src/explain.rs). Run it after adding or removing a page; `--check` fails if the file is stale
# (scripts/check.sh runs it).
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="$ROOT/compiler/src/error_pages.auk"
gen() {
  echo "/// The \`auk explain\` pages (docs/errors/<code>.md), embedded in the binary: one \`#embed\` extern"
  echo "/// per page. Generated by scripts/gen_error_pages.sh; do not edit."
  echo
  codes=()
  for f in $(cd "$ROOT/docs/errors" && ls E*.md | LC_ALL=C sort); do
    c="${f%.md}"
    codes+=("$c")
    echo "extern fn $(echo "$c" | tr 'E' 'e')(): str = \"#embed ../../docs/errors/$f\""
  done
  echo
  echo "/// Every code with a page, in order."
  echo "pub let CODES = ["
  for c in "${codes[@]}"; do echo "  \"$c\","; done
  echo "]"
  echo
  echo "/// The markdown page for \`code\`."
  echo "pub fn page(code: str): str? uses ffi = match code {"
  for c in "${codes[@]}"; do echo "  \"$c\" => $(echo "$c" | tr 'E' 'e')()"; done
  echo "  _ => none"
  echo "}"
}
if [ "${1:-}" = "--check" ]; then
  if ! diff -q <(gen) "$out" > /dev/null; then
    echo "compiler/src/error_pages.auk is stale: run scripts/gen_error_pages.sh"
    exit 1
  fi
else
  gen > "$out"
fi
