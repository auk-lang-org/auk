def test_hidden_balanced():
    assert balanced("([]{})")
    assert not balanced("([)]")
    assert balanced("")
    assert balanced("no brackets")
    assert not balanced("((")
    assert not balanced("))")
    assert not balanced("}{")
    assert balanced("a(b[c]d)e")
    assert balanced("{[()()]}")
    assert not balanced("{[()()]}]")
    assert not balanced("(")
    assert not balanced("]")
    assert balanced("f(x) = [y{z}]")
