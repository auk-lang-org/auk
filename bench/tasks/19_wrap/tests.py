def test_hidden_wrap():
    assert wrap("the quick brown fox", 10) == ["the quick", "brown fox"]
    assert wrap("", 5) == []
    assert wrap("   \n\t ", 3) == []
    assert wrap("a b c", 1) == ["a", "b", "c"]
    assert wrap("a b c", 3) == ["a b", "c"]
    assert wrap("a b c", 5) == ["a b c"]
    assert wrap("hello   world\nfoo", 11) == ["hello world", "foo"]
    assert wrap("abcdefghij", 4) == ["abcd", "efgh", "ij"]
    assert wrap("abcde f", 4) == ["abcd", "e f"]
    assert wrap("ab abcdefgh x", 4) == ["ab", "abcd", "efgh", "x"]
    assert wrap("ééé üü", 6) == ["ééé üü"]
    assert wrap("ééé üü", 5) == ["ééé", "üü"]
    assert wrap("exactly ten", 7) == ["exactly", "ten"]
